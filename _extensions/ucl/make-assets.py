"""Regenerate ucl-assets.scss from assets/ and fonts/. Logos and UCL Sans
are inlined as data URIs so the theme needs no extra resource files."""
import base64
import pathlib

here = pathlib.Path(__file__).parent


def uri(path, mime):
    data = base64.b64encode((here / path).read_bytes()).decode()
    return f'url("data:{mime};base64,{data}")'


fonts = [
    ("Regular", 400, "normal"),
    ("Italic", 400, "italic"),
    ("SemiBold", 600, "normal"),
    ("SemiBoldItalic", 600, "italic"),
    ("Bold", 700, "normal"),
    ("BoldItalic", 700, "italic"),
]

font_faces = "\n".join(
    f"""@font-face {{
  font-family: "UCL Sans";
  src: {uri(f"fonts/UCLSans-{name}.woff2", "font/woff2")} format("woff2");
  font-weight: {weight};
  font-style: {style};
  font-display: swap;
}}
"""
    for name, weight, style in fonts
)

(here / "ucl-assets.scss").write_text(f"""/*-- scss:rules --*/

// Generated by make-assets.py: do not edit by hand.

// UCL Sans (SIL Open Font License, see fonts/OFL.txt)
{font_faces}
// Logo sits bottom-right on every slide (112x31pt; 224x63pt on the title slide).

.reveal .slides section:not(.stack) {{
  background: {uri("assets/ucl-logo-purple.png", "image/png")} no-repeat right 53px bottom 53px / 187px auto;
}}

.reveal .slides section.has-dark-background:not(.stack) {{
  background: {uri("assets/ucl-logo-white-large.png", "image/png")} no-repeat right 53px bottom 53px / 187px auto;
}}

.reveal .slides section.quarto-title-block {{
  background-size: 373px auto;
}}

.reveal .slides section.no-logo {{
  background: none !important;
}}
""")
